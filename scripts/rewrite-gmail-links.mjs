#!/usr/bin/env node
// ============================================================================
// rewrite-gmail-links.mjs — one-time fix for links baked in before gmailLink()
// learned to skip the slow /u/0/#all/ path.
// ============================================================================
//
// WHY THIS EXISTS
// ----------------
// gmailLink() (scripts/lib/gmail.mjs) used to always build
// https://mail.google.com/mail/u/0/#all/<id> — a hardcoded account-slot guess
// plus a full-archive lookup, both of which can make "Open email" take a very
// long time to load. That function is fixed now (it can build #inbox/<id>
// when the message is still in the inbox, and takes a real slot number), but
// the fix only applies to links generated by FUTURE runs. Every link already
// written to Firestore — the 80-item "Needs your eyes" queue, and every
// statusHistory entry on every paper — is still the old, slow format. This
// script rewrites those in place. Run it once; nothing about normal daily
// syncing depends on it.
//
// WHAT IT TOUCHES
//   • unmatched/{id}.link
//   • papers/{id}.statusHistory[].source.link   (only entries with automated
//     evidence links; whole array is rewritten since Firestore has no partial
//     array-element update)
//   • papers/{id}.lastEmailLink                 (kept in sync with whichever
//     history entry it was copied from)
//
// HOW A LINK GETS FIXED
//   1. The old link already encodes the Gmail message ID (#all/<id> or
//      #inbox/<id>) — parsed back out with a regex, no guessing.
//   2. The document's own `account` / `source.account` label (Dhibin /
//      Professor) says which inbox to ask, via the SAME ACCOUNTS config used
//      by the daily sync — so `slot` fixes made there apply here too.
//   3. One live Gmail API call per message (format: 'minimal' — cheap) checks
//      whether the message still carries the INBOX label right now. If the
//      message was archived since it arrived, #all/ is kept — the earlier
//      classifier logic behind #inbox/ links was correctness, not a fixed
//      choice, and an inbox link to an archived message would just fail.
//
// MODES
//   node scripts/rewrite-gmail-links.mjs              → dry run (prints diffs only)
//   node scripts/rewrite-gmail-links.mjs --write       → applies the rewrite
//
// A message the Gmail API can no longer find (deleted, or moved to Trash and
// expired) is left untouched and reported, not treated as an error that
// aborts the run — an old broken link is no worse than it already was.
// ============================================================================

import { initializeApp, cert } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';
import { makeGmailClient, gmailLink, getAccountEmail } from './lib/gmail.mjs';

const WRITE = process.argv.includes('--write');

// Keep this identical to sync-journal-emails.mjs — same accounts, same slots.
// If you've since learned the real /u/<n>/ slot numbers, set them here too;
// this script will bake the corrected slot into every rewritten link.
const ACCOUNTS = [
  { key: 'A', label: 'Dhibin', refreshToken: process.env.GMAIL_REFRESH_TOKEN_A, slot: 0 },
  { key: 'B', label: 'Professor', refreshToken: process.env.GMAIL_REFRESH_TOKEN_B, slot: 0 },
].filter((a) => a.refreshToken);

// Matches both the old #all/<id> and the already-fixed #inbox/<id> — running
// this script twice is safe and mostly a no-op the second time.
const LINK_RE = /^https:\/\/mail\.google\.com\/mail\/u\/\d+\/#(?:all|inbox)\/([^?]+)/;

function initFirestore() {
  const raw = process.env.FIREBASE_SERVICE_ACCOUNT;
  if (!raw) throw new Error('FIREBASE_SERVICE_ACCOUNT is not set');
  let creds;
  try {
    creds = JSON.parse(raw);
  } catch {
    creds = JSON.parse(Buffer.from(raw, 'base64').toString('utf8'));
  }
  initializeApp({ credential: cert(creds) });
  return getFirestore();
}

function requireEnv(name) {
  const v = process.env[name];
  if (!v) throw new Error(`${name} is not set`);
  return v;
}

async function main() {
  const startedAt = new Date();
  console.log('═'.repeat(74));
  console.log('  RESEARCH TRACKER — one-time Gmail link rewrite');
  console.log('═'.repeat(74));
  console.log(`  mode : ${WRITE ? 'LIVE — writes to Firestore' : 'DRY RUN — no writes'}`);
  console.log('─'.repeat(74));

  const db = initFirestore();
  const clientId = requireEnv('GMAIL_CLIENT_ID');
  const clientSecret = requireEnv('GMAIL_CLIENT_SECRET');
  if (!ACCOUNTS.length) throw new Error('No Gmail refresh tokens configured');

  // One Gmail client + confirmed real address per account, keyed by the
  // human label ("Dhibin" / "Professor") stored on every Firestore doc.
  const byLabel = new Map();
  for (const account of ACCOUNTS) {
    const gmail = makeGmailClient({ clientId, clientSecret, refreshToken: account.refreshToken });
    const accountEmail = await getAccountEmail(gmail);
    byLabel.set(account.label, { gmail, accountEmail, slot: account.slot });
    console.log(`  ${account.label.padEnd(10)} → ${accountEmail} (slot ${account.slot})`);
  }
  console.log('─'.repeat(74));

  const stats = { seen: 0, upgraded: 0, unchanged: 0, noAccount: 0, notParsed: 0, apiError: 0 };
  // messageId cache — the same email often appears as both an unmatched item
  // AND a statusHistory entry (e.g. it was queued, then later the paper got
  // the ID and was linked). One label lookup per unique message is enough.
  const labelCache = new Map(); // `${label}:${messageId}` -> inInbox (bool) | null on error

  async function isInInbox(label, messageId) {
    const cacheKey = `${label}:${messageId}`;
    if (labelCache.has(cacheKey)) return labelCache.get(cacheKey);
    const acc = byLabel.get(label);
    if (!acc) { stats.noAccount++; labelCache.set(cacheKey, null); return null; }
    try {
      const res = await acc.gmail.users.messages.get({ userId: 'me', id: messageId, format: 'minimal' });
      const inInbox = (res.data.labelIds || []).includes('INBOX');
      labelCache.set(cacheKey, inInbox);
      return inInbox;
    } catch (err) {
      console.warn(`  ⚠ could not look up message ${messageId} (${label}): ${err.message}`);
      stats.apiError++;
      labelCache.set(cacheKey, null);
      return null;
    }
  }

  /** Rewrite one link string. Returns the new link, or the old one unchanged
   *  (never null — every path falls back to leaving the link exactly as it
   *  was if anything about the rewrite is uncertain). */
  async function rewriteLink(oldLink, label) {
    stats.seen++;
    const m = oldLink && LINK_RE.exec(oldLink);
    if (!m) { stats.notParsed++; return oldLink; }
    const messageId = m[1];
    const acc = byLabel.get(label);
    if (!acc) { stats.noAccount++; return oldLink; }

    const inInbox = await isInInbox(label, messageId);
    if (inInbox === null) return oldLink; // API couldn't confirm — leave it

    const newLink = gmailLink(messageId, acc.accountEmail, { inInbox, slot: acc.slot });
    if (newLink === oldLink) { stats.unchanged++; return oldLink; }
    stats.upgraded++;
    return newLink;
  }

  // ── unmatched ────────────────────────────────────────────────────────────
  const unmatchedSnap = await db.collection('unmatched').get();
  console.log(`\n  unmatched: ${unmatchedSnap.size} document(s)`);
  for (const doc of unmatchedSnap.docs) {
    const u = doc.data();
    if (!u.link) continue;
    const newLink = await rewriteLink(u.link, u.account);
    if (newLink !== u.link) {
      console.log(`    ${doc.id}  (${u.account})`);
      console.log(`      old: ${u.link}`);
      console.log(`      new: ${newLink}`);
      if (WRITE) await doc.ref.update({ link: newLink });
    }
  }

  // ── papers.statusHistory[] + lastEmailLink ─────────────────────────────
  const papersSnap = await db.collection('papers').get();
  console.log(`\n  papers: ${papersSnap.size} document(s)`);
  for (const doc of papersSnap.docs) {
    const p = doc.data();
    const history = Array.isArray(p.statusHistory) ? p.statusHistory : [];
    if (!history.length) continue;

    let changedAny = false;
    const oldToNew = new Map();
    const newHistory = [];
    for (const entry of history) {
      const oldLink = entry?.source?.link;
      const label = entry?.source?.account;
      if (!oldLink || !label) { newHistory.push(entry); continue; }
      const newLink = await rewriteLink(oldLink, label);
      if (newLink !== oldLink) {
        changedAny = true;
        oldToNew.set(oldLink, newLink);
        newHistory.push({ ...entry, source: { ...entry.source, link: newLink } });
      } else {
        newHistory.push(entry);
      }
    }

    const update = {};
    if (changedAny) update.statusHistory = newHistory;
    if (p.lastEmailLink && oldToNew.has(p.lastEmailLink)) {
      update.lastEmailLink = oldToNew.get(p.lastEmailLink);
    }

    if (Object.keys(update).length) {
      console.log(`    #${p.id} "${(p.title || '').slice(0, 50)}" — ${Object.keys(update).join(', ')} updated`);
      if (WRITE) await doc.ref.update(update);
    }
  }

  const finishedAt = new Date();
  console.log(`\n${'═'.repeat(74)}\n  SUMMARY\n${'═'.repeat(74)}`);
  console.log(`  links seen         : ${stats.seen}`);
  console.log(`  upgraded ${WRITE ? '(written)' : '(would write)'} : ${stats.upgraded}`);
  console.log(`  already optimal    : ${stats.unchanged}`);
  console.log(`  unrecognised label : ${stats.noAccount}`);
  console.log(`  unparsable link    : ${stats.notParsed}`);
  console.log(`  Gmail API errors   : ${stats.apiError} (message not found / moved — left unchanged)`);
  console.log(`  duration           : ${((finishedAt - startedAt) / 1000).toFixed(1)}s`);
  if (!WRITE && stats.upgraded > 0) {
    console.log(`\n  → Dry run only. Re-run with --write to apply these ${stats.upgraded} change(s).`);
  }
  console.log('═'.repeat(74));
}

main().catch((err) => {
  console.error('\n✖ FATAL:', err.message);
  console.error(err.stack);
  process.exit(1);
});
